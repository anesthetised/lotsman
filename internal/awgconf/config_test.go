func TestRange(t *testing.T) {
	for in, want := range map[string]string{"5": "5", "5-9": "5-9", " 7 - 8 ": "7-8"} {
		r, err := ParseRange(in)
		if err != nil {
			t.Errorf("ParseRange(%q): %v", in, err)
			continue
		}
		if r.String() != want {
			t.Errorf("ParseRange(%q).String() = %q, want %q", in, r.String(), want)
		}
	}
}

func TestKeys(t *testing.T) {
	priv, err := GeneratePrivateKey()
	if err != nil {
		t.Fatal(err)
	}
	if priv[0]&7 != 0 || priv[31]&128 != 0 || priv[31]&64 == 0 {
		t.Error("private key is not clamped")
	}
	parsed, err := ParseKey(priv.String())
	if err != nil || parsed != priv {
		t.Errorf("base64 round trip failed: %v", err)
	}
	if priv.Public() != priv.Public() || priv.Public() == priv {
		t.Error("public key derivation is not deterministic or equals private key")
	}
	if len(priv.Hex()) != 64 {
		t.Errorf("hex length %d", len(priv.Hex()))
	}
}
