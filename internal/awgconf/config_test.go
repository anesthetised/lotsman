func mustPrefix(t *testing.T, s string) netip.Prefix {
	t.Helper()
	return netip.MustParsePrefix(s)
}

func TestParseProviderConfig(t *testing.T) {
	cfg, err := Parse(strings.NewReader(providerConf))
	if err != nil {
		t.Fatal(err)
	}
	priv, _ := ParseKey(privB64)
	pub, _ := ParseKey(pubB64)
	psk, _ := ParseKey(pskB64)
	want := &Config{
		Interface: Interface{
			PrivateKey: priv,
			Addresses:  []netip.Prefix{mustPrefix(t, "10.8.1.7/32"), mustPrefix(t, "fd00::7/128")},
			DNS:        []netip.Addr{netip.MustParseAddr("1.1.1.1"), netip.MustParseAddr("1.0.0.1")},
			MTU:        1380,
			Params: Params{
				Jc: 4, Jmin: 40, Jmax: 70,
				S1: 15, S2: 25, S3: 10, S4: 8,
				H1: Range{100, 200}, H2: Range{300, 400}, H3: Range{500, 600}, H4: Range{700, 800},
				I: [5]string{"<b 0xc000000001><r 64><t>", "<rd 12><rc 8>"},
			},
		},
		Peers: []Peer{{
			PublicKey:           pub,
			PresharedKey:        psk,
			Endpoint:            "vpn.example.org:51820",
			AllowedIPs:          []netip.Prefix{mustPrefix(t, "0.0.0.0/0"), mustPrefix(t, "::/0")},
			PersistentKeepalive: 25,
		}},
	}
	if diff := cmp.Diff(want, cfg, cmpopts.EquateComparable(netip.Prefix{}, netip.Addr{})); diff != "" {
		t.Errorf("Parse mismatch (-want +got):\n%s", diff)
	}
}

func TestParseLegacy15Config(t *testing.T) {
	const conf = `[Interface]
PrivateKey = ` + privB64 + `
Address = 10.0.0.2
Jc = 5
Jmin = 50
Jmax = 1000
S1 = 61
S2 = 24
H1 = 1234567
H2 = 2345678
H3 = 3456789
H4 = 4567890

[Peer]
PublicKey = ` + pubB64 + `
Endpoint = 203.0.113.5:443
AllowedIPs = 0.0.0.0/0
`
	cfg, err := Parse(strings.NewReader(conf))
	if err != nil {
		t.Fatal(err)
	}
	if got := cfg.Interface.Addresses; len(got) != 1 || got[0] != mustPrefix(t, "10.0.0.2/32") {
		t.Errorf("bare address not widened to /32: %v", got)
	}
	if cfg.Interface.H1 != (Range{1234567, 1234567}) {
		t.Errorf("single H1 = %v", cfg.Interface.H1)
	}
	if cfg.Interface.S3 != 0 || cfg.Interface.S4 != 0 {
		t.Errorf("S3/S4 should stay zero: %d %d", cfg.Interface.S3, cfg.Interface.S4)
	}
}

func TestParseErrors(t *testing.T) {
	cases := map[string]string{
		"unknown interface key": "[Interface]\nPrivateKey = " + privB64 + "\nHeaderProtectionKey = abc\n",
		"unknown peer key":      "[Interface]\nPrivateKey = " + privB64 + "\n[Peer]\nPublicKey = " + pubB64 + "\nFoo = 1\n",
		"missing private key":   "[Interface]\nAddress = 10.0.0.2/32\n",
		"bad key length":        "[Interface]\nPrivateKey = AAAA\n",
		"bad range":             "[Interface]\nPrivateKey = " + privB64 + "\nH1 = 200-100\n",
		"key outside section":   "PrivateKey = " + privB64 + "\n",
		"unknown section":       "[Foo]\n",
		"no equals":             "[Interface]\nPrivateKey\n",
		"bad address":           "[Interface]\nPrivateKey = " + privB64 + "\nAddress = nope\n",
	}
	for name, conf := range cases {
		t.Run(name, func(t *testing.T) {
			if _, err := Parse(strings.NewReader(conf)); err == nil {
				t.Fatal("expected error")
			}
		})
	}
}

func TestRoundTrip(t *testing.T) {
	cfg, err := Parse(strings.NewReader(providerConf))
	if err != nil {
		t.Fatal(err)
	}
	again, err := Parse(strings.NewReader(cfg.String()))
	if err != nil {
		t.Fatalf("re-parse of rendered config: %v\n%s", err, cfg.String())
	}
	if diff := cmp.Diff(cfg, again, cmpopts.EquateComparable(netip.Prefix{}, netip.Addr{})); diff != "" {
		t.Errorf("round trip mismatch (-first +second):\n%s", diff)
	}
}

